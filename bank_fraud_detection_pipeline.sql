CREATE OR REPLACE FILE FORMAT FRAUD_DEMO.RAW.TRANSACTIONS_CSV_FORMAT
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL', 'null')
