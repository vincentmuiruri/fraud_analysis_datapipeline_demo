CREATE OR REPLACE VIEW FRAUD_DEMO.ANALYTICS.V_HIGH_RISK_TRANSACTIONS AS
SELECT
  TRANSACTION_ID,
  TRANSACTION_TS,
  CUSTOMER_ID,
  ACCOUNT_ID,
  AMOUNT,
  CURRENCY,
  TRANSACTION_TYPE,
  MERCHANT_NAME,
  COUNTRY,
  DEVICE_ID,
  IP_ADDRESS,
  IS_FRAUD,
  RISK_SCORE,
  TRANSACTION_STATUS,
  FRAUD_CLASSIFICATION
FROM FRAUD_DEMO.CORE.TRANSACTIONS
WHERE HIGH_RISK_FLAG
   OR IS_FRAUD
   OR TRANSACTION_STATUS IN ('PENDING_REVIEW', 'DECLINED', 'BLOCKED');

CREATE OR REPLACE VIEW FRAUD_DEMO.ANALYTICS.V_FRAUD_DASHBOARD_KPIS AS
SELECT
  COUNT(*) AS TOTAL_TRANSACTIONS,
  COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,
  SUM(AMOUNT) AS TOTAL_TRANSACTION_AMOUNT,
  COUNT_IF(FRAUD_CLASSIFICATION = 'CONFIRMED_FRAUD') AS CONFIRMED_FRAUD_COUNT,
  COUNT_IF(FRAUD_CLASSIFICATION = 'SUSPICIOUS') AS SUSPICIOUS_COUNT,
  COUNT_IF(TRANSACTION_STATUS IN ('DECLINED', 'BLOCKED')) AS DECLINED_OR_BLOCKED_COUNT,
  DIV0(COUNT_IF(FRAUD_CLASSIFICATION = 'CONFIRMED_FRAUD'), COUNT(*)) AS CONFIRMED_FRAUD_RATE,
  AVG(RISK_SCORE) AS AVG_RISK_SCORE
FROM FRAUD_DEMO.CORE.TRANSACTIONS;

