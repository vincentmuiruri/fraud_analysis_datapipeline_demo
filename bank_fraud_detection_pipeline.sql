CREATE OR REPLACE STAGE FRAUD_DEMO.RAW.TRANSACTIONS_STAGE
  FILE_FORMAT = FRAUD_DEMO.RAW.TRANSACTIONS_CSV_FORMAT
  COMMENT = 'Internal stage for incoming transaction CSV files';

CREATE OR REPLACE TABLE FRAUD_DEMO.RAW.TRANSACTIONS_RAW (
  TRANSACTION_ID       NUMBER(38,0),
  TRANSACTION_TS       TIMESTAMP_NTZ,
  CUSTOMER_ID          NUMBER(38,0),
  ACCOUNT_ID           NUMBER(38,0),
  AMOUNT               NUMBER(12,2),
  CURRENCY             VARCHAR(3),
  TRANSACTION_TYPE     VARCHAR(30),
  MERCHANT_NAME        VARCHAR(150),
  MERCHANT_CATEGORY    VARCHAR(50),
  CITY                 VARCHAR(100),
  COUNTRY              VARCHAR(100),
  DEVICE_ID            VARCHAR(100),
  IP_ADDRESS           VARCHAR(45),
