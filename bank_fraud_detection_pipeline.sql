-- ============================================================
-- 02. INSERT 10,000 SYNTHETIC TRANSACTIONS
-- Each run of this seed section adds 10,000 rows with unique IDs in the
-- 100001-110000 range. Run this section only once for a clean demo.
-- Values are synthetic and intentionally include fraud/high-risk patterns.
-- ============================================================
INSERT INTO FRAUD_DEMO.RAW.TRANSACTIONS_RAW
  (TRANSACTION_ID, TRANSACTION_TS, CUSTOMER_ID, ACCOUNT_ID, AMOUNT,
   CURRENCY, TRANSACTION_TYPE, MERCHANT_NAME, MERCHANT_CATEGORY, CITY,
   COUNTRY, DEVICE_ID, IP_ADDRESS, IS_FRAUD, RISK_SCORE, TRANSACTION_STATUS)
WITH generated AS (
  SELECT ROW_NUMBER() OVER (ORDER BY SEQ4()) AS RN
  FROM TABLE(GENERATOR(ROWCOUNT => 10000))
)
SELECT
  100000 + RN AS TRANSACTION_ID,
  DATEADD('second', -MOD(RN * 7919, 7776000), CURRENT_TIMESTAMP()::TIMESTAMP_NTZ) AS TRANSACTION_TS,
  5000 + MOD(RN * 37, 7000) AS CUSTOMER_ID,
  90000 + MOD(RN * 19, 9000) AS ACCOUNT_ID,
  ROUND(5 + MOD(RN * 173, 250000) / 100.0, 2) AS AMOUNT,
  CASE MOD(RN, 4) WHEN 0 THEN 'KES' WHEN 1 THEN 'USD' WHEN 2 THEN 'UGX' ELSE 'TZS' END AS CURRENCY,
  CASE MOD(RN, 4) WHEN 0 THEN 'TRANSFER' WHEN 1 THEN 'PURCHASE' WHEN 2 THEN 'ATM_WITHDRAWAL' ELSE 'ONLINE_PAYMENT' END AS TRANSACTION_TYPE,
  CASE MOD(RN, 8) WHEN 0 THEN 'Online Transfer' WHEN 1 THEN 'Grocery Mart' WHEN 2 THEN 'Fuel Station' WHEN 3 THEN 'Electronics Hub' WHEN 4 THEN 'Travel Desk' WHEN 5 THEN 'Pharmacy Plus' WHEN 6 THEN 'Fashion Store' ELSE 'Digital Services' END AS MERCHANT_NAME,
  CASE MOD(RN, 8) WHEN 0 THEN 'TRANSFER' WHEN 1 THEN 'GROCERY' WHEN 2 THEN 'FUEL' WHEN 3 THEN 'ELECTRONICS' WHEN 4 THEN 'TRAVEL' WHEN 5 THEN 'PHARMACY' WHEN 6 THEN 'RETAIL' ELSE 'DIGITAL' END AS MERCHANT_CATEGORY,
  CASE MOD(RN, 6) WHEN 0 THEN 'Nairobi' WHEN 1 THEN 'Mombasa' WHEN 2 THEN 'Kampala' WHEN 3 THEN 'Dar es Salaam' WHEN 4 THEN 'London' ELSE 'Toronto' END AS CITY,
  CASE MOD(RN, 6) WHEN 0 THEN 'Kenya' WHEN 1 THEN 'Kenya' WHEN 2 THEN 'Uganda' WHEN 3 THEN 'Tanzania' WHEN 4 THEN 'United Kingdom' ELSE 'Canada' END AS COUNTRY,
  'DEV' || LPAD(MOD(RN * 13, 5000)::VARCHAR, 5, '0') AS DEVICE_ID,
  '198.51.' || MOD(RN, 255)::VARCHAR || '.' || (1 + MOD(RN * 7, 253))::VARCHAR AS IP_ADDRESS,
  MOD(RN, 97) = 0 AS IS_FRAUD,
  ROUND(MOD(RN * 29, 10000) / 10000.0, 4) AS RISK_SCORE,
  CASE
    WHEN MOD(RN, 97) = 0 THEN 'BLOCKED'
    WHEN MOD(RN, 13) = 0 THEN 'DECLINED'
    WHEN MOD(RN, 11) = 0 THEN 'PENDING_REVIEW'
    ELSE 'APPROVED'
  END AS TRANSACTION_STATUS
FROM generated;

-- ============================================================
-- 03. STAGING VIEW: STANDARDIZE TYPES AND DERIVE RULE FLAGS
-- ============================================================
CREATE OR REPLACE VIEW FRAUD_DEMO.STAGING.V_TRANSACTIONS_STANDARDIZED AS
SELECT
  TRANSACTION_ID,
  TRANSACTION_TS,
  CUSTOMER_ID,
  ACCOUNT_ID,
  AMOUNT,
  UPPER(TRIM(CURRENCY)) AS CURRENCY,
  UPPER(TRIM(TRANSACTION_TYPE)) AS TRANSACTION_TYPE,
  TRIM(MERCHANT_NAME) AS MERCHANT_NAME,
  UPPER(TRIM(MERCHANT_CATEGORY)) AS MERCHANT_CATEGORY,
  TRIM(CITY) AS CITY,
  TRIM(COUNTRY) AS COUNTRY,
  TRIM(DEVICE_ID) AS DEVICE_ID,
  TRIM(IP_ADDRESS) AS IP_ADDRESS,
  COALESCE(IS_FRAUD, FALSE) AS IS_FRAUD,
  RISK_SCORE,
  UPPER(TRIM(TRANSACTION_STATUS)) AS TRANSACTION_STATUS,
  INGESTED_AT,
  IFF(AMOUNT >= 5000, TRUE, FALSE) AS HIGH_VALUE_FLAG,
  IFF(RISK_SCORE >= 0.80, TRUE, FALSE) AS HIGH_RISK_FLAG
FROM FRAUD_DEMO.RAW.TRANSACTIONS_RAW
WHERE TRANSACTION_ID IS NOT NULL
  AND TRANSACTION_TS IS NOT NULL
  AND AMOUNT >= 0
  AND RISK_SCORE BETWEEN 0 AND 1;

-- ============================================================
-- 04. STREAM + TASK: INCREMENTALLY LOAD NEW TRANSACTIONS TO CORE
-- Existing seed rows are loaded into CORE first; the stream below
-- captures subsequent DML changes. This avoids replaying the seed rows.
-- ============================================================
CREATE OR REPLACE TABLE FRAUD_DEMO.CORE.TRANSACTIONS (
  TRANSACTION_ID       NUMBER(38,0) NOT NULL,
  TRANSACTION_TS       TIMESTAMP_NTZ,
  CUSTOMER_ID          NUMBER(38,0),
  ACCOUNT_ID           NUMBER(38,0),
  AMOUNT               NUMBER(12,2),
  CURRENCY             VARCHAR(3),
  TRANSACTION_TYPE     VARCHAR(30),
  MERCHANT_NAME        VARCHAR(150),
  MERCHANT_CATEGORY    VARCHAR(50),
  CITY                 VARCHAR(100),
  COUNTRY              VARCHAR(100),
  DEVICE_ID            VARCHAR(100),
  IP_ADDRESS           VARCHAR(45),
  IS_FRAUD              BOOLEAN,
  RISK_SCORE            NUMBER(5,4),
  TRANSACTION_STATUS   VARCHAR(30),
  INGESTED_AT           TIMESTAMP_NTZ,
  HIGH_VALUE_FLAG       BOOLEAN,
  HIGH_RISK_FLAG        BOOLEAN,
  FRAUD_CLASSIFICATION VARCHAR(30),
  PROCESSED_AT          TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO FRAUD_DEMO.CORE.TRANSACTIONS
  (TRANSACTION_ID, TRANSACTION_TS, CUSTOMER_ID, ACCOUNT_ID, AMOUNT,
   CURRENCY, TRANSACTION_TYPE, MERCHANT_NAME, MERCHANT_CATEGORY, CITY,
   COUNTRY, DEVICE_ID, IP_ADDRESS, IS_FRAUD, RISK_SCORE, TRANSACTION_STATUS,
   INGESTED_AT, HIGH_VALUE_FLAG, HIGH_RISK_FLAG, FRAUD_CLASSIFICATION)
SELECT
  TRANSACTION_ID, TRANSACTION_TS, CUSTOMER_ID, ACCOUNT_ID, AMOUNT,
  CURRENCY, TRANSACTION_TYPE, MERCHANT_NAME, MERCHANT_CATEGORY, CITY,
  COUNTRY, DEVICE_ID, IP_ADDRESS, IS_FRAUD, RISK_SCORE, TRANSACTION_STATUS,
  INGESTED_AT, HIGH_VALUE_FLAG, HIGH_RISK_FLAG,
  CASE
    WHEN IS_FRAUD THEN 'CONFIRMED_FRAUD'
    WHEN HIGH_RISK_FLAG OR TRANSACTION_STATUS = 'PENDING_REVIEW' THEN 'SUSPICIOUS'
    ELSE 'LEGITIMATE_OR_UNCONFIRMED'
  END AS FRAUD_CLASSIFICATION
FROM FRAUD_DEMO.STAGING.V_TRANSACTIONS_STANDARDIZED;

CREATE OR REPLACE STREAM FRAUD_DEMO.RAW.TRANSACTIONS_RAW_STREAM
  ON TABLE FRAUD_DEMO.RAW.TRANSACTIONS_RAW
  APPEND_ONLY = TRUE
  COMMENT = 'Captures newly inserted raw transaction rows';

CREATE OR REPLACE TASK FRAUD_DEMO.CORE.PROCESS_NEW_TRANSACTIONS_TASK
  WAREHOUSE = FRAUD_WH
  SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('FRAUD_DEMO.RAW.TRANSACTIONS_RAW_STREAM')
AS
INSERT INTO FRAUD_DEMO.CORE.TRANSACTIONS
  (TRANSACTION_ID, TRANSACTION_TS, CUSTOMER_ID, ACCOUNT_ID, AMOUNT,
   CURRENCY, TRANSACTION_TYPE, MERCHANT_NAME, MERCHANT_CATEGORY, CITY,
   COUNTRY, DEVICE_ID, IP_ADDRESS, IS_FRAUD, RISK_SCORE, TRANSACTION_STATUS,
   INGESTED_AT, HIGH_VALUE_FLAG, HIGH_RISK_FLAG, FRAUD_CLASSIFICATION)
SELECT
  s.TRANSACTION_ID,
  s.TRANSACTION_TS,
  s.CUSTOMER_ID,
  s.ACCOUNT_ID,
  s.AMOUNT,
  UPPER(TRIM(s.CURRENCY)),
  UPPER(TRIM(s.TRANSACTION_TYPE)),
  TRIM(s.MERCHANT_NAME),
  UPPER(TRIM(s.MERCHANT_CATEGORY)),
  TRIM(s.CITY),
  TRIM(s.COUNTRY),
  TRIM(s.DEVICE_ID),
  TRIM(s.IP_ADDRESS),
  COALESCE(s.IS_FRAUD, FALSE),
  s.RISK_SCORE,
  UPPER(TRIM(s.TRANSACTION_STATUS)),
  s.INGESTED_AT,
  s.AMOUNT >= 5000,
  s.RISK_SCORE >= 0.80,
  CASE
    WHEN COALESCE(s.IS_FRAUD, FALSE) THEN 'CONFIRMED_FRAUD'
    WHEN s.RISK_SCORE >= 0.80 OR UPPER(TRIM(s.TRANSACTION_STATUS)) = 'PENDING_REVIEW'
      THEN 'SUSPICIOUS'
    ELSE 'LEGITIMATE_OR_UNCONFIRMED'
  END
FROM FRAUD_DEMO.RAW.TRANSACTIONS_RAW_STREAM s
WHERE s.TRANSACTION_ID IS NOT NULL
  AND s.TRANSACTION_TS IS NOT NULL
  AND s.AMOUNT >= 0
  AND s.RISK_SCORE BETWEEN 0 AND 1;

-- Start scheduled processing only after reviewing the SQL above.
ALTER TASK FRAUD_DEMO.CORE.PROCESS_NEW_TRANSACTIONS_TASK RESUME;

-- ============================================================
-- 05. DYNAMIC TABLES: DECLARATIVE ANALYTICS
-- ============================================================
CREATE OR REPLACE DYNAMIC TABLE FRAUD_DEMO.ANALYTICS.DT_DAILY_TRANSACTION_SUMMARY
  TARGET_LAG = '5 minutes'
  WAREHOUSE = FRAUD_WH
  REFRESH_MODE = AUTO
AS
SELECT
  TO_DATE(TRANSACTION_TS) AS TRANSACTION_DATE,
  COUNTRY,
  TRANSACTION_TYPE,
  COUNT(*) AS TRANSACTION_COUNT,
  SUM(AMOUNT) AS TOTAL_AMOUNT,
  AVG(AMOUNT) AS AVG_AMOUNT,
  AVG(RISK_SCORE) AS AVG_RISK_SCORE,
  COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS
FROM FRAUD_DEMO.CORE.TRANSACTIONS
GROUP BY TO_DATE(TRANSACTION_TS), COUNTRY, TRANSACTION_TYPE;

CREATE OR REPLACE DYNAMIC TABLE FRAUD_DEMO.ANALYTICS.DT_FRAUD_RISK_SUMMARY
  TARGET_LAG = '2 minutes'
  WAREHOUSE = FRAUD_WH
  REFRESH_MODE = AUTO
AS
SELECT
  COUNTRY,
  COUNT(*) AS TRANSACTION_COUNT,
  COUNT_IF(FRAUD_CLASSIFICATION = 'CONFIRMED_FRAUD') AS CONFIRMED_FRAUD_COUNT,
  COUNT_IF(FRAUD_CLASSIFICATION = 'SUSPICIOUS') AS SUSPICIOUS_COUNT,
  COUNT_IF(TRANSACTION_STATUS IN ('DECLINED', 'BLOCKED')) AS DECLINED_OR_BLOCKED_COUNT,
  SUM(IFF(TRANSACTION_STATUS IN ('DECLINED', 'BLOCKED'), AMOUNT, 0)) AS DECLINED_OR_BLOCKED_AMOUNT,
  DIV0(COUNT_IF(FRAUD_CLASSIFICATION = 'CONFIRMED_FRAUD'), COUNT(*)) AS CONFIRMED_FRAUD_RATE,
  AVG(RISK_SCORE) AS AVG_RISK_SCORE
FROM FRAUD_DEMO.CORE.TRANSACTIONS
GROUP BY COUNTRY;

